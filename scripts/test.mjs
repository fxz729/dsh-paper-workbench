import { readdirSync, mkdirSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const library=['library-tools','library-service','metadata','enrichment-queue','library-observer','discovery-enrichment','global-translation-observer'];
const browser=['batch-identity','details-ui'];
const files=(process.argv.includes('--library')?library.map(n=>n+'.test.mjs'):readdirSync(new URL('../tests/',import.meta.url)).filter(n=>n.endsWith('.test.mjs')&&!browser.includes(n.replace('.test.mjs','')))).map(n=>'tests/'+n);
const owned=mkdtempSync(join(tmpdir(),'dsh-workbench-tests-'));
const env={...process.env,DSH_HOME:join(owned,'home')};mkdirSync(env.DSH_HOME,{recursive:true});
for(const name of ['OPENAI_API_KEY','TYPESAFE_API_KEY','DSH_EMBED_API_KEY','MINERU_API_KEY','DSH_MINERU_LOCAL_URL','DSH_PAPER_READER_DATA'])delete env[name];
const result=spawnSync(process.execPath,['--loader','./tests/sdk-contract-fixture-loader.mjs','--test','--test-timeout=60000','--test-concurrency=1',...files],{cwd:root,env,encoding:'utf8',maxBuffer:24*1024*1024,timeout:300000});
mkdirSync(new URL('../artifacts/',import.meta.url),{recursive:true});
const mode=process.argv.includes('--library')?'library':'unit';
writeFileSync(new URL('../artifacts/'+mode+'-tests.log',import.meta.url),(result.stdout||'')+'\n'+(result.stderr||''));
console.log(result.stdout||'');
if(result.stderr)console.error(result.stderr);
if(result.error)console.error(result.error.message);
console.log('TEST_SCOPE: isolated SDK contract double; actual local filesystem/runtime; no external model requests');
console.log('TEST_EXIT='+result.status);
rmSync(owned,{recursive:true,force:true});
process.exitCode=result.status===0?0:1;
